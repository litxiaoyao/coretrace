#!/usr/bin/env python3
"""Build manuscript tables directly from completed experiment summaries.

Run from any directory: python analysis/build_tables.py
No model, GPU, or restored prediction archives are required.
"""
from pathlib import Path
import csv
import json
import math
import statistics as stats

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'paper' / 'tables'
OUT.mkdir(parents=True, exist_ok=True)
MODELS = ['qwen3_4b', 'qwen3_8b', 'llama3_8b']
NAMES = {'qwen3_4b': 'Qwen3-4B', 'qwen3_8b': 'Qwen3-8B', 'llama3_8b': 'Llama-3.1-8B'}
METHODS = {'native': 'Native', 'FullFT': 'Full fine-tuning', 'native_text': 'Evidence filtering',
           'head_tuning': 'Head tuning', 'scoped_body': 'Scoped adaptation',
           'graphfirst': 'Graph-first selection',
           'final_attention': 'Attention-only reader',
           'final_metadata': 'Metadata-only reader', 'final': r'\method\ (Ours)'}
ROWS = list(csv.DictReader((ROOT/'outputs/tables/tables.csv').open()))
INPUTS = {'outputs/tables/tables.csv'}

def read(rel):
    INPUTS.add(str(rel))
    return json.loads((ROOT/rel).read_text())

def row(model, method, benchmark='core', query='composed'):
    found = [r for r in ROWS if r['model']==model and r['method']==method
             and r['benchmark']==benchmark and r['query']==query]
    if len(found)!=1:
        raise ValueError((model,method,benchmark,query,len(found)))
    return found[0]

def cell(r, bold=False, sd=True, digits=1):
    mu = 100*float(r['mean_accuracy'])
    val = f'{mu:.{digits}f}'
    if bold:
        val = r'\mathbf{'+val+'}'
    if sd and r.get('sample_std_accuracy'):
        val += r'{\color{black!60}\,\pm\,'+f"{100*float(r['sample_std_accuracy']):.{digits}f}"+'}'
    return '$'+val+'$'

def save(name, text):
    (OUT/name).write_text('% Generated by analysis/build_tables.py.\n'
                         +r'\begingroup\renewcommand{\arraystretch}{1.08}'+'\n'
                         +text+'\n'+r'\endgroup'+'\n')

def line(xs):
    return ' & '.join(map(str,xs))+r' \\'

def header(xs):
    return line([r'\textbf{'+str(x)+'}' if x else '' for x in xs])

def section(label, n):
    return [r'\midrule',r'\multicolumn{'+str(n)+r'}{l}{\textit{'+label+r'}} \\']

def shaded(method):
    return r'\rowcolor{tableours}' if method=='final' else (r'\rowcolor{tablebase}' if method=='native' else '')

def metric(value, bold=False, digits=1, sd=None):
    s=f'{value:.{digits}f}'
    if bold:s=r'\mathbf{'+s+'}'
    if sd is not None:s+=r'{\color{black!60}\,\pm\,'+f'{sd:.{digits}f}'+'}'
    return '$'+s+'$'

def delta(value, digits=1):
    color='gain' if value>=0 else 'loss'
    return r'{\color{'+color+'}$'+f'{value:+.{digits}f}'+'$}'

def best(model, method, methods, benchmark='core', query='composed'):
    v=float(row(model,method,benchmark,query)['mean_accuracy'])
    return abs(v-max(float(row(model,k,benchmark,query)['mean_accuracy']) for k in methods))<1e-10

def main_results():
    methods=['native','FullFT','native_text','head_tuning','scoped_body','graphfirst','final']
    s=[r'\begin{tabular}{lrrrrrr}',r'\toprule',
       line(['',r'\multicolumn{2}{c}{\textbf{Qwen3-4B}}',r'\multicolumn{2}{c}{\textbf{Qwen3-8B}}',r'\multicolumn{2}{c}{\textbf{Llama-3.1-8B}}']),
       r'\cmidrule(lr){2-3}\cmidrule(lr){4-5}\cmidrule(lr){6-7}',
       header(['Method',r'Composed $\uparrow$',r'All three $\uparrow$',r'Composed $\uparrow$',r'All three $\uparrow$',r'Composed $\uparrow$',r'All three $\uparrow$']),r'\midrule']
    for method in methods:
        if method=='head_tuning': s+=section('Mechanistically informed adaptation',7)
        cells=[]
        for model in MODELS:
            for query in ['composed','all3']:
                val=row(model,method,query=query)
                cells.append(cell(val,bold=best(model,method,methods,query=query)))
        label=r'\textbf{'+METHODS[method]+'}' if method=='final' else METHODS[method]
        s.append(shaded(method)+line([label]+cells))
    gains=[100*(float(row(m,'final',query=q)['mean_accuracy'])-float(row(m,'native',query=q)['mean_accuracy'])) for m in MODELS for q in ['composed','all3']]
    s.append(line([r'\textit{Gain over Native (pp)}']+[delta(g) for g in gains]))
    s += [r'\bottomrule',r'\end{tabular}']
    save('main_results.tex','\n'.join(s))


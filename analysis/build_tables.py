#!/usr/bin/env python3
"""Build manuscript tables directly from completed experiment summaries.

Run from any directory: python analysis/build_tables.py
No model, GPU, or restored prediction archives are required.
"""
from pathlib import Path
import csv
import json
import math
import statistics as stats

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'paper' / 'tables'
OUT.mkdir(parents=True, exist_ok=True)
MODELS = ['qwen3_4b', 'qwen3_8b', 'llama3_8b']
NAMES = {'qwen3_4b': 'Qwen3-4B', 'qwen3_8b': 'Qwen3-8B', 'llama3_8b': 'Llama-3.1-8B'}
METHODS = {'native': 'Native', 'native_text': 'Evidence filtering',
           'head_tuning': 'Head tuning', 'scoped_body': 'Scoped adaptation',
           'graphfirst': 'Graph-first selection', 'final': r'\method',
           'final_attention': 'Attention-only reader',
           'final_metadata': 'Metadata-only reader', 'FullFT': 'Full fine-tuning'}
ROWS = list(csv.DictReader((ROOT/'outputs/tables/tables.csv').open()))
INPUTS = {'outputs/tables/tables.csv'}

def read(rel):
    INPUTS.add(str(rel))
    return json.loads((ROOT/rel).read_text())

def row(model, method, benchmark='core', query='composed'):
    found = [r for r in ROWS if r['model']==model and r['method']==method
             and r['benchmark']==benchmark and r['query']==query]
    if len(found)!=1:
        raise ValueError((model,method,benchmark,query,len(found)))
    return found[0]

def cell(r, bold=False, sd=True, digits=1):
    mu = 100*float(r['mean_accuracy'])
    val = f'{mu:.{digits}f}'
    if bold:
        val = r'\mathbf{'+val+'}'
    if sd and r.get('sample_std_accuracy'):
        val += r'\,\pm\,'+f"{100*float(r['sample_std_accuracy']):.{digits}f}"
    return '$'+val+'$'

def save(name, text):
    (OUT/name).write_text('% Generated by analysis/build_tables.py.\n'+text+'\n')

def line(xs):
    return ' & '.join(map(str,xs))+r' \\'

def main_results():
    methods=['native','native_text','head_tuning','scoped_body','graphfirst','final','FullFT']
    s=[r'\begin{tabular}{lrrrrrr}',r'\toprule',
       line(['',r'\multicolumn{2}{c}{Qwen3-4B}',r'\multicolumn{2}{c}{Qwen3-8B}',r'\multicolumn{2}{c}{Llama-3.1-8B}']),
       r'\cmidrule(lr){2-3}\cmidrule(lr){4-5}\cmidrule(lr){6-7}',
       line(['Method','Composed','All three','Composed','All three','Composed','All three']),r'\midrule']
    for method in methods:
        if method=='FullFT': s.append(r'\midrule')
        cells=[]
        for model in MODELS:
            for query in ['composed','all3']:
                val=row(model,method,query=query)
                best=max(float(row(model,k,query=query)['mean_accuracy']) for k in methods)
                cells.append(cell(val,bold=abs(float(val['mean_accuracy'])-best)<1e-10))
        s.append(line([METHODS[method]]+cells))
    s += [r'\bottomrule',r'\end{tabular}']
    save('main_results.tex','\n'.join(s))

def retention():
    methods=['native','head_tuning','final','FullFT']
    s=[r'\begin{tabular}{lrrrrrrrrr}',r'\toprule',
       line(['',r'\multicolumn{3}{c}{Qwen3-4B}',r'\multicolumn{3}{c}{Qwen3-8B}',r'\multicolumn{3}{c}{Llama-3.1-8B}']),
       r'\cmidrule(lr){2-4}\cmidrule(lr){5-7}\cmidrule(lr){8-10}',
       line(['Method']+['Hotpot','MMLU','GSM8K']*3),r'\midrule']
    for method in methods:
        cells=[]
        for model in MODELS:
            for b in ['hotpot','mmlu','gsm8k']:
                r=row(model,method,b,b)
                best=max(float(row(model,k,b,b)['mean_accuracy']) for k in methods)
                cells.append(cell(r,bold=abs(float(r['mean_accuracy'])-best)<1e-10,sd=False,digits=2))
        s.append(line([METHODS[method]]+cells))
    s += [r'\bottomrule',r'\end{tabular}']
    save('main_retention.tex','\n'.join(s))

def complete_core():
    s=[r'\begin{tabular}{llrrrr}',r'\toprule',line(['Model','Method','Composed','First hop','Target hop','All three']),r'\midrule']
    for model in MODELS:
        for i,method in enumerate(METHODS):
            s.append(line([NAMES[model] if i==0 else '',METHODS[method]]+
                          [cell(row(model,method,query=q),digits=2) for q in ['composed','direct_first','direct_target','all3']]))
        if model!=MODELS[-1]:s.append(r'\midrule')
    s += [r'\bottomrule',r'\end{tabular}']
    save('complete_core.tex','\n'.join(s))

def ambiguity():
    data=read('analysis/internal/ambiguous_evidence.json')['rows']
    s=[r'\begin{tabular}{llrr}',r'\toprule',line(['Model','Selection rule','Bridge address','Composed EM']),r'\midrule']
    for model in MODELS:
        for i,method in enumerate(['graphfirst','final_metadata','final_attention','final']):
            r=next(r for r in data if r['model']==model and r['method']==method)
            s.append(line([NAMES[model] if i==0 else '',METHODS[method],
                           f"{100*r['bridge_selection_accuracy']:.1f}",
                           f"${100*r['answer_accuracy_mean']:.1f}\\pm {100*r['answer_accuracy_sample_std']:.1f}$"]))
        if model!=MODELS[-1]:s.append(r'\midrule')
    s += [r'\bottomrule',r'\end{tabular}']
    save('ambiguous_selection.tex','\n'.join(s))

def readouts():
    data=read('analysis/internal/readout_validation.json')
    s=[r'\begin{tabular}{llrrrrrr}',r'\toprule',line(['','',r'\multicolumn{3}{c}{All test sources ($n=1{,}000$)}',r'\multicolumn{3}{c}{Native composition failures}']),
       r'\cmidrule(lr){3-5}\cmidrule(lr){6-8}',line(['Model','Model state','Full','Attention','Metadata','Full','Attention','Metadata']),r'\midrule']
    for model in MODELS:
        for i,state in enumerate(['native_readout','seed42/readout']):
            r=next(r for r in data if r['directory']==f'outputs/{model}/{state}')
            allv=[100*r['recomputed'][f]['test']['correct']/r['recomputed'][f]['test']['n'] for f in ['full','attention','metadata']]
            sub=[100*r['native_composition_failure_readout'][f]['correct']/r['native_composition_failure_readout'][f]['n'] for f in ['full','attention','metadata']]
            s.append(line([NAMES[model] if not i else '', 'Native' if not i else 'Scoped adaptation']+[f'{x:.1f}' for x in allv+sub]))
        if model!=MODELS[-1]:s.append(r'\midrule')
    s += [r'\bottomrule',r'\end{tabular}']
    save('readout_diagnostics.tex','\n'.join(s))

def factorization():
    keys={'mass_effect_receiver_conditional':'Mass effect, receiver pattern',
          'mass_effect_donor_conditional':'Mass effect, direct-query pattern',
          'conditional_effect_native_mass':'Pattern effect, native mass',
          'conditional_effect_fixed_mass':'Pattern effect, calibrated mass',
          'interaction':'Mass $\\times$ pattern interaction'}
    s=[r'\begin{tabular}{lrrr}',r'\toprule',line(['Contrast']+[NAMES[m] for m in MODELS]),r'\midrule']
    data={m:read(f'outputs/{m}/causal_factorization/summary.json')['factorial_accuracy']['contrasts'] for m in MODELS}
    for key,label in keys.items():
        vals=[]
        for m in MODELS:
            r=data[m][key];lo,hi=r['paired_cluster_CI95'];vals.append(f"${100*r['estimate']:+.1f}\\;[{100*lo:+.1f}, {100*hi:+.1f}]$")
        s.append(line([label]+vals))
    s += [r'\bottomrule',r'\end{tabular}']
    save('factorial_contrasts.tex','\n'.join(s))

def content():
    s=[r'\begin{tabular}{llrrrr}',r'\toprule',line(['Model','Method','Original EM','Edited-value EM','Old-value persistence','Joint original/edited']),r'\midrule']
    names={'native':'Native','native_budget':'Mass calibration','body':'Scoped adaptation','final':r'\method'}
    for model in MODELS:
        ds=[read(f'outputs/{model}/seed{seed}/causal_content/summary.json')['summary'] for seed in [42,43,44]]
        for i,v in enumerate(names):
            ss=[next(r for r in d if r['variant']==v and r['pool']=='all_sources') for d in ds]
            vals=[]
            for key in ['original_old_correct','edited_new_follow','edited_old_persistence','original_correct_then_new']:
                a=[100*r[key]/r['n'] for r in ss]
                vals.append(f'${stats.mean(a):.1f}\\pm {stats.stdev(a):.1f}$' if v in ['body','final'] else f'{a[0]:.1f}')
            s.append(line([NAMES[model] if not i else '',names[v]]+vals))
        if model!=MODELS[-1]:s.append(r'\midrule')
    s += [r'\bottomrule',r'\end{tabular}']
    save('content_outcomes.tex','\n'.join(s))

def configurations():
    costs=list(csv.DictReader((ROOT/'outputs/tables/training_costs.csv').open()));INPUTS.add('outputs/tables/training_costs.csv')
    s=[r'\begin{tabular}{lrrrr}',r'\toprule',line(['Model','Selected heads','Reader weights','Trainable weights','Model fraction']),r'\midrule']
    for m in MODELS:
        heads=read(f'outputs/{m}/discovery/SELECTION_FROZEN.json')['winner']['n']
        n=int(next(r for r in costs if r['model']==m and r['method']=='head_tuning')['trainable_parameters'])
        total=int(next(r for r in costs if r['model']==m and r['method']=='FullFT')['trainable_parameters'])
        s.append(line([NAMES[m],heads,2*heads+2,f'{n:,}',f'{100*n/total:.3f}\\%']))
    s += [r'\bottomrule',r'\end{tabular}'];save('parameters.tex','\n'.join(s))

def per_run():
    s=[r'\begin{tabular}{llrrr}',r'\toprule',line(['Model','Method','Run 42','Run 43','Run 44']),r'\midrule']
    for m in MODELS:
        for i,k in enumerate(['head_tuning','scoped_body','graphfirst','final','final_attention','final_metadata','FullFT']):
            a=[]
            for seed in [42,43,44]:
                pipe='evaluation_fullft' if k=='FullFT' else 'evaluation'
                data=read(f'outputs/{m}/seed{seed}/{pipe}/core/summary.json')
                wanted='fullft' if k=='FullFT' else k
                r=next(r for r in data['summary'] if r['method'].lower()==wanted.lower() and r['query']=='composed')
                a.append(f"{100*r['accuracy']:.1f}")
            s.append(line([NAMES[m] if i==0 else '',METHODS[k]]+a))
        if m!=MODELS[-1]:s.append(r'\midrule')
    s += [r'\bottomrule',r'\end{tabular}'];save('per_run_core.tex','\n'.join(s))

def capability_full():
    s=[r'\begin{tabular}{llrrr}',r'\toprule',line(['Model','Method','HotpotQA','MMLU','GSM8K']),r'\midrule']
    for m in MODELS:
        for i,k in enumerate(['native','head_tuning','final','FullFT']):
            s.append(line([NAMES[m] if not i else '',METHODS[k]]+[cell(row(m,k,b,b),digits=2) for b in ['hotpot','mmlu','gsm8k']]))
        if m!=MODELS[-1]:s.append(r'\midrule')
    s += [r'\bottomrule',r'\end{tabular}'];save('capability_full.tex','\n'.join(s))

def paired_effects():
    data=read('analysis/internal/clustered_contrasts.json')['models']
    s=[r'\begin{tabular}{lrrr}',r'\toprule',line(['Paired contrast']+[NAMES[m] for m in MODELS]),r'\midrule']
    for key,label in [('repair_minus_native',r'\method\ $-$ Native'),('repair_minus_graphfirst',r'\method\ $-$ Graph-first'),('bridge_mass_minus_native','Bridge calibration $-$ Native')]:
        vals=[]
        for m in MODELS:
            r=data[m][key];lo,hi=r['paired_cluster_CI95']
            vals.append(f"${100*r['estimate']:.2f}\\;[{100*lo:.2f}, {100*hi:.2f}]$")
        s.append(line([label]+vals))
    s += [r'\bottomrule',r'\end{tabular}'];save('paired_effects.tex','\n'.join(s))

def efficiency():
    rel='outputs/tables/inference_costs.csv';INPUTS.add(rel)
    data=list(csv.DictReader((ROOT/rel).open()))
    s=[r'\begin{tabular}{llrrrrr}',r'\toprule',line(['Model','Method','Input tokens (M)','Output tokens (K)','Readout prefills','Batch sizes','Seconds']),r'\midrule']
    for m in MODELS:
        for i,k in enumerate(['native','head_tuning','final','FullFT']):
            a=[r for r in data if r['model']==m and r['method']==k and r['benchmark']=='core']
            avg=lambda key:stats.mean(float(r[key]) for r in a)
            batches='/'.join(sorted({r['generation_batch_sizes'] for r in a}))
            s.append(line([NAMES[m] if not i else '',METHODS[k],f"{avg('input_tokens')/1e6:.3f}",f"{avg('generated_tokens')/1e3:.2f}",f"{avg('address_prefills'):.0f}",batches,f"{avg('seconds'):.0f}"]))
        if m!=MODELS[-1]:s.append(r'\midrule')
    s += [r'\bottomrule',r'\end{tabular}'];save('inference_costs.tex','\n'.join(s))
    rel='outputs/tables/training_costs.csv';INPUTS.add(rel);data=list(csv.DictReader((ROOT/rel).open()))
    s=[r'\begin{tabular}{llrrrr}',r'\toprule',line(['Model','Training','Sources','Updates','Weights (M)','Seconds, mean (range)']),r'\midrule']
    for m in MODELS:
        for i,k in enumerate(['head_tuning','FullFT']):
            a=[r for r in data if r['model']==m and r['method']==k];t=[float(r['seconds']) for r in a]
            s.append(line([NAMES[m] if not i else '',METHODS[k],a[0]['sources'],a[0]['optimizer_steps'],f"{int(a[0]['trainable_parameters'])/1e6:.2f}",f'{stats.mean(t):.0f} ({min(t):.0f}--{max(t):.0f})']))
        if m!=MODELS[-1]:s.append(r'\midrule')
    s += [r'\bottomrule',r'\end{tabular}'];save('training_costs.tex','\n'.join(s))

def scoring_diagnostics():
    s=[r'\begin{tabular}{llrrrr}',r'\toprule',line(['Model','Method','Completed EM','Text EM','Text F1','EOS completion']),r'\midrule']
    for m in MODELS:
        for i,k in enumerate(['native','final','FullFT']):
            ds=[]
            for seed in ([42] if k=='native' else [42,43,44]):
                pipe='evaluation_fullft' if k=='FullFT' else 'evaluation'
                x=read(f'outputs/{m}/seed{seed}/{pipe}/core/summary.json')
                ds.append(next(r for r in x['summary'] if r['method'].lower()==k.lower() and r['query']=='composed'))
            vals=[stats.mean(100*r['accuracy'] for r in ds),stats.mean(100*r['text_alias_correct']/r['n'] for r in ds),stats.mean(100*r['mean_text_f1'] for r in ds),stats.mean(100*r['eos_complete']/r['n'] for r in ds)]
            s.append(line([NAMES[m] if not i else '',METHODS[k]]+[f'{v:.2f}' for v in vals]))
        if m!=MODELS[-1]:s.append(r'\midrule')
    s += [r'\bottomrule',r'\end{tabular}'];save('scoring_diagnostics.tex','\n'.join(s))

def main():
    for fn in [main_results,retention,complete_core,ambiguity,readouts,factorization,content,configurations,per_run,capability_full,paired_effects,efficiency,scoring_diagnostics]:fn()
    (ROOT/'analysis/figure_data').mkdir(exist_ok=True)
    (ROOT/'analysis/figure_data/table_inputs.json').write_text(json.dumps(sorted(INPUTS),indent=2)+'\n')
    print(f'Wrote {len(list(OUT.glob("*.tex")))} tables from {len(INPUTS)} source files to {OUT}')

if __name__=='__main__':main()
